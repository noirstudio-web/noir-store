  m.el.addEventListener('click', e => { const b = e.target.closest('[data-lg]'); if (!b) return; m.$('#lg-doc').innerHTML = LEGAL[b.dataset.lg]; m.el.querySelectorAll('[data-lg]').forEach(x => x.classList.toggle('on', x === b)); m.$('#lg-doc').scrollTop = 0; });
